/** フォルダ種別 + ファイル名 → 「名前（説明）」表示 */
function assetLabel_(kind, fileName) {
  let key = String(fileName).replace(/\.[A-Za-z0-9]+$/, '').trim();
  const vm = key.match(/^(.+?)_(白|黒|赤)$/); // 焼き込みバリアント（85%/25%/15%）
  const variant = vm ? { '白': '・白85%', '黒': '・黒25%', '赤': '・赤15%' }[vm[2]] : '';
  if (vm) key = vm[1];
  const cat = kind === 'ICON_P' ? ICON_P_CATALOG : kind === 'ICON_W' ? ICON_W_CATALOG : kind === 'BG' ? BG_CATALOG : SELECT_CATALOG;
  const desc = cat[key];
  return desc ? fileName + '（' + desc + (typeof variant === 'string' ? variant : '') + '）' : fileName;
}
