const assert = require('assert');
const { makeEnv, loadGas } = require('./fake_gas.cjs');

const env = makeEnv();
const root = env.makeFolder('root', null, 'ROOT');
const out = root.addFolder('【出力】生成物', 'OUT');
const caseFolder = out.addFolder('架空テスト社', 'CASE');
const hearingId = 'Hearing012345678901234567890123';
const ss = env.makeSpreadsheet(hearingId, ['【オファー記入用】', '【問題教育の記入用】']);
env.files[hearingId] = { getLastUpdated: () => new Date('2026-10-23T00:00:00.000Z') };
const mgmt = env.makeSpreadsheet('MGMTxxxxxxxxxxxxxxxxxxxxxxxxxxxx', ['管理']);
mgmt.getSheets()[0].getRange(1, 1, 2, 2).setValues([['ヒアリングID', '案件名'], [hearingId, '架空テスト社_ヒアリングシート']]);
Object.assign(env.props, { INPUT_FOLDER_ID: 'IN', OUTPUT_FOLDER_ID: 'OUT', TEMPLATE_SLIDE_ID: 'T', ASSETS_FOLDER_ID: 'AS', MGMT_SHEET_ID: 'MGMTxxxxxxxxxxxxxxxxxxxxxxxxxxxx' });
ss.sheets['【オファー記入用】'].getRange(1, 1, 2, 2).setValues([['会社名', '架空テスト社'], ['課題', '説明が長い']]);
ss.sheets['【問題教育の記入用】'].getRange('A1').setValue('原本の根拠');
const G = loadGas(env);

const first = G.相談室_原本スナップショットを書く_(caseFolder, '架空テスト社', hearingId);
assert.equal(first.caseName, '架空テスト社');
assert.equal(first.hearingId, hearingId);
assert.ok(first.text.includes('説明が長い'));
const file = caseFolder.getFilesByName('【相談室】ヒアリング原本.json').next();
const saved = JSON.parse(file.getBlob().getDataAsString());
assert.equal(saved.source, 'hearing-sheet');
assert.equal(saved.revision, first.revision);
assert.equal(saved.sourceModifiedAt, '2026-10-23T00:00:00.000Z');
const creates = env.log.filter(x => x[0] === 'create' && x[1].endsWith('【相談室】ヒアリング原本.json')).length;
G.相談室_原本スナップショットを書く_(caseFolder, '架空テスト社', hearingId);
assert.equal(env.log.filter(x => x[0] === 'create' && x[1].endsWith('【相談室】ヒアリング原本.json')).length, creates);
ss.sheets['【オファー記入用】'].getRange('B2').setValue('更新された原本');
const changed = G.相談室_原本スナップショットを書く_(caseFolder, '架空テスト社', hearingId);
assert.notEqual(changed.revision, first.revision);
assert.ok(JSON.parse(file.getBlob().getDataAsString()).text.includes('更新された原本'));
assert.throws(() => G.相談室_原本スナップショットを書く_(caseFolder, '架空テスト社', 'not-an-id'), /ヒアリングID/);
const verified = G.スライド_相談室承認前ヒアリングを読む('架空テスト社');
assert.equal(verified.ok, true);
assert.equal(verified.hearingId, hearingId);
assert.equal(verified.revision, changed.revision);
assert.equal(verified.sourceModifiedAt, '2026-10-23T00:00:00.000Z');
assert.throws(() => G.スライド_相談室承認前ヒアリングを読む('存在しない社'), /管理シート/);

// 固定隔離入口は通常台帳を見ず、56の固定root/台帳検査後に一件だけ再読する。
const isoParent = env.makeFolder('【隔離試験】配置永続化', null, 'ISO_PARENT');
const isoRoot = isoParent.addFolder('【隔離通し】診断から資料音声_20261023', 'ISO_ROOT');
const isoStart = isoRoot.addFolder('【出力】', 'ISO_START');
isoRoot.addFolder('【出力】生成物', 'ISO_OUTPUT');
isoRoot.addFolder('【素材】投影資料', 'ISO_ASSETS');
const isoLedger = env.makeSpreadsheet('ISO_LEDGER', ['管理']);
isoLedger.getSheets()[0].getRange(1, 1, 2, 8).setValues([['ヒアリングID', '案件名', '状態', '構成', 'Slides', '文', '更新', '流れ'], [hearingId, '隔離通し診断テスト社_ヒアリングシート', 'レビュー待ち', '', '', '', '', '新']]);
env.files.ISO_LEDGER = { getParents: () => ({ hasNext: (() => { let n = 0; return () => n++ === 0; })(), next: () => isoRoot }) };
G.隔離通し_生成_案件名 = '隔離通し診断テスト社';
G.隔離通し_生成_rootID = 'ISO_ROOT';
G.隔離通し_生成_親rootID = 'ISO_PARENT';
G.隔離通し_生成_台帳ID = 'ISO_LEDGER';
G.隔離通し_生成_開始箱ID = 'ISO_START';
G.隔離通し_生成_生成物rootID = 'ISO_OUTPUT';
G.隔離通し_生成_ヒアリングID = hearingId;
const isolated = G.スライド_隔離相談室承認前ヒアリングを読む();
assert.equal(isolated.ok, true);
assert.equal(isolated.caseName, '隔離通し診断テスト社');
assert.equal(isolated.hearingId, hearingId);
assert.equal(G.ISOLATION_TEST_CONFIG_, null);
console.log('ok consultation hearing snapshot');
